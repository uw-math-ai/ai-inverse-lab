"""Challenge specs -> inverse-problem instances -> noisy observations.

A *spec* is what the challenger controls: the fptsim toggles for one graph.

    {"graphs":     {... an fptsim `graphs:` block: families/presets, weights, mu, B, q, dt ...},
     "simulation": {"T": 17, "T_mode": "steps", "N": 20000}}

Seeds are never part of the spec. The harness assigns them, so a challenger cannot cherry-pick a
lucky graph or noise draw. The spec is validated by fptsim's own strict validator, and the graph is
generated by fptsim.generators.generate_graph, so every instance is reproducible from
(spec, seed) with plain fptsim.
"""
from __future__ import annotations

import copy
import hashlib
import json
from dataclasses import dataclass

import numpy as np

from fptsim.config import FAMILY_PARAMS, ConfigError, effective_T, spec_max, validate_config
from fptsim.exact import exact_single
from fptsim.generators import GenerationError, generate_graph
from fptsim.graphs import PRESETS, Graph, pattern_coords
from fptsim.kernel import KernelError, build_kernel, transition_table

from .forward import InverseProblem
from .solvers import Observation

SPEC_KEYS = {"graphs", "simulation"}
SIM_KEYS = {"T", "T_mode", "N"}


class SpecError(ValueError):
    """The spec is malformed, outside the harness limits, or cannot generate a graph."""

    def __init__(self, code: str, message: str):
        super().__init__(message)
        self.code = code


@dataclass
class Instance:
    spec: dict
    seed: int
    graph: Graph
    problem: InverseProblem      # what solvers see
    mu_true: np.ndarray          # hidden ground truth (full vector; only U is unknown)
    N: int
    r_exact: np.ndarray          # (T, k, k)
    killed_exact: np.ndarray     # (k, k)
    censored_exact: np.ndarray   # (k, k)
    P: np.ndarray                # (n+1, n+1) augmented chain (for Monte Carlo)

    def fingerprint(self) -> str:
        """Hash of the generated instance (graph + hidden mu + horizon), used for de-duplication."""
        h = hashlib.sha256()
        for arr in (self.graph.W, self.mu_true, self.graph.B, self.graph.q):
            h.update(np.ascontiguousarray(np.round(arr, 12)).tobytes())
        h.update(f"{self.problem.T}".encode())
        return h.hexdigest()[:16]

    def summary(self) -> dict:
        g, p = self.graph, self.problem
        mu_U = self.mu_true[p.U] if p.m else np.zeros(1)
        ratio = (self.mu_true / np.maximum(g.weighted_degrees, 1e-300))[p.U] if p.m else np.zeros(1)
        return {"family": g.family, "n": g.n, "num_edges": g.num_edges, "k": p.k, "unknowns": p.m,
                "T": p.T, "N": self.N, "dt": p.dt, "q_max": float(g.q.max()),
                "mu_U_mean": float(mu_U.mean()), "mu_over_wdeg_cv": float(ratio.std() / max(ratio.mean(), 1e-300)),
                "hit_mass_mean": float(self.r_exact.sum(axis=0).mean())}


def canonical(spec: dict) -> str:
    return json.dumps(spec, sort_keys=True, default=str)


def _vertex_bound(gcfg_raw: dict) -> int:
    """Upper bound on the number of vertices a raw graphs block can produce (before generating)."""
    if gcfg_raw.get("presets"):
        return max(PRESETS[name]().n for name in gcfg_raw["presets"])
    worst = 0
    for name, entry in (gcfg_raw.get("families") or {}).items():
        if name == "pattern":
            worst = max(worst, max(len(pattern_coords(p)) for p in entry["patterns"]))
        elif name in ("grid", "grid_holes"):
            worst = max(worst, int(spec_max(entry["rows"])) * int(spec_max(entry["cols"])))
        elif name == "ladder":
            worst = max(worst, 2 * int(spec_max(entry["length"])))
        elif "n" in FAMILY_PARAMS.get(name, {}):
            worst = max(worst, int(spec_max(entry["n"])) + (1 if name == "random_regular" else 0))
    return worst


def check_spec(spec, limits: dict) -> dict:
    """Validate a spec against the schema and the harness limits; return the fptsim-resolved config."""
    if not isinstance(spec, dict):
        raise SpecError("invalid_spec", f"spec must be a mapping, got {type(spec).__name__}")
    extra = set(spec) - SPEC_KEYS
    if extra:
        raise SpecError("invalid_spec", f"spec: unknown keys {sorted(extra)} (allowed: graphs, simulation)")
    sim = spec.get("simulation") or {}
    if not isinstance(sim, dict) or set(sim) - SIM_KEYS:
        raise SpecError("invalid_spec", f"spec.simulation: only {sorted(SIM_KEYS)} may be set")
    raw = {"run_name": "autodata_item", "num_graphs": 1, "master_seed": 0,
           "graphs": copy.deepcopy(spec.get("graphs")), "simulation": {**sim, "replicates": 1}}
    try:
        cfg = validate_config(raw)
    except ConfigError as exc:
        raise SpecError("invalid_spec", f"fptsim rejected the spec: {exc}") from exc
    T = effective_T(cfg["simulation"]["T"], cfg["simulation"]["T_mode"])
    N = cfg["simulation"]["N"]
    bound = _vertex_bound(cfg["graphs"])
    if bound > limits["max_n"]:
        raise SpecError("too_large", f"spec can produce {bound} vertices > limits.max_n = {limits['max_n']}")
    if T > limits["max_T"]:
        raise SpecError("too_large", f"T = {T} steps > limits.max_T = {limits['max_T']}")
    if not (limits["min_N"] <= N <= limits["max_N"]):
        raise SpecError("bad_N", f"N = {N} outside [limits.min_N, limits.max_N] = "
                                 f"[{limits['min_N']}, {limits['max_N']}]")
    return cfg


def build_instance(spec: dict, seed: int, limits: dict) -> Instance:
    cfg = check_spec(spec, limits)
    gcfg = cfg["graphs"]
    try:
        g = generate_graph(gcfg, seed, 0)
    except (GenerationError, KernelError) as exc:
        raise SpecError("generation_failed", f"fptsim could not generate a graph: {exc}") from exc
    if g.n > limits["max_n"]:
        raise SpecError("too_large", f"graph has {g.n} vertices > limits.max_n")
    if len(g.B) > limits["max_k"]:
        raise SpecError("too_large", f"|B| = {len(g.B)} > limits.max_k = {limits['max_k']}")
    kern = build_kernel(g.W, g.mu, g.q, gcfg["dt"])
    T = effective_T(cfg["simulation"]["T"], cfg["simulation"]["T_mode"])
    ex = exact_single(kern, g.B, T)               # raises if fptsim's two exact checks disagree
    prob = InverseProblem(W=g.W, mu_known=g.mu, B=g.B, q=g.q, dt=kern.dt, T=T)
    return Instance(spec=copy.deepcopy(spec), seed=int(seed), graph=g, problem=prob,
                    mu_true=g.mu.copy(), N=int(cfg["simulation"]["N"]), r_exact=ex["r"],
                    killed_exact=ex["killed"], censored_exact=ex["censored"], P=kern.P)


# ---------------------------------------------------------------- observations
def observe(inst: Instance, noise: str, seed: int) -> Observation:
    """One noisy measurement of the instance.

    multinomial  per ordered pair, draw N outcomes from the exact law (hit at t = 1..T, killed,
                 censored). Statistically identical to running N walks, and much faster.
    monte_carlo  run the N walks with fptsim's numpy Monte Carlo backend (slow; for checking).
    exact        noise-free r (N = None).
    """
    T, k = inst.problem.T, inst.problem.k
    if noise == "exact":
        return Observation(counts=np.zeros((T, k, k), dtype=np.int64), N=None, r=inst.r_exact.copy())
    if noise == "multinomial":
        rng = np.random.default_rng(seed)
        probs = np.concatenate([inst.r_exact.reshape(T, k * k),
                                inst.killed_exact.reshape(1, k * k),
                                inst.censored_exact.reshape(1, k * k)], axis=0).T   # (k*k, T+2)
        probs = np.clip(probs, 0.0, None)
        probs /= probs.sum(axis=1, keepdims=True)
        draws = np.stack([rng.multinomial(inst.N, p) for p in probs])               # (k*k, T+2)
        return Observation(counts=draws[:, :T].T.reshape(T, k, k), N=inst.N)
    if noise == "monte_carlo":
        from fptsim.mc_common import MCItem, counts_to_outcomes
        from fptsim.mc_numpy import NumpyMC
        nbr, cdf = transition_table(inst.P)
        item = MCItem(key=(0, 0, 0, 0), nbr=nbr, cdf=cdf, B=inst.graph.B, T=T, m=inst.N, start=0,
                      checkpoints=np.array([inst.N]), seed=int(seed))
        hits, _, _, _ = counts_to_outcomes(NumpyMC().run_item(item), T)
        return Observation(counts=hits, N=inst.N)
    raise ValueError(f"unknown noise model {noise!r} (multinomial | monte_carlo | exact)")
