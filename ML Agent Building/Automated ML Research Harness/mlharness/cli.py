"""Command line interface: ``python -m mlharness <command>``."""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

from . import HARNESS_ROOT


def _spec_from_args(args, pipeline=None):
    from .spec import compile_spec, load_raw
    from .llm import make_llm
    raw = load_raw(args.spec)
    if args.backend:
        raw.setdefault("llm", {})["backend"] = args.backend
    if args.model:
        raw.setdefault("llm", {})["model"] = args.model
    if args.budget:
        raw.setdefault("budget", {})["compute_seconds"] = args.budget
    if args.workers:
        raw.setdefault("hardware", {})["workers"] = args.workers
    for attr, section, key in (("rounds", "research", "max_rounds"), ("memory", "memory", "path"),
                               ("research_llm_calls", "research", "llm_calls")):
        if getattr(args, attr, None) is not None:
            raw.setdefault(section, {})[key] = getattr(args, attr)
    if getattr(args, "no_literature", False):
        raw.setdefault("literature", {})["enabled"] = False
    if getattr(args, "no_memory", False):
        raw.setdefault("memory", {})["enabled"] = False
    if getattr(args, "no_forward_model", False):
        raw.setdefault("constraints", {})["allow_forward_model"] = False
    if getattr(args, "remote", None):
        raw.setdefault("hardware", {})["remote"] = {**(raw.get("hardware", {}).get("remote") or {}),
                                                    "enabled": True, "host": args.remote}
    llm_cfg = dict(raw.get("llm") or {})
    llm = make_llm(llm_cfg) if "simulator" not in raw else None
    return compile_spec(raw, llm=llm, pipeline=pipeline)


def _print_final(spec, run_dir, fin):
    print("\n=== research complete ===")
    print(f"run dir : {run_dir}")
    print(f"report  : {run_dir / 'report.md'}")
    labels = fin.get("labels") or fin["members"]
    print(f"model   : {fin['model_path']}  ({fin['kind']}: {', '.join(labels)})")
    print(f"val {spec.primary}: {fin['val']:.5g}   test: " +
          ", ".join(f"{k}={v:.5g}" for k, v in fin["test"].items() if v is not None))
    if spec.success["threshold"] is not None:
        print(f"success criterion met: {fin['audit']['success']}")


def cmd_research(args):
    from .scheduler_v2 import ResearchSchedulerV2
    spec = _spec_from_args(args, pipeline="v2")
    run_dir = Path(args.run_dir) if args.run_dir else HARNESS_ROOT / "runs" / f"{spec.name}_v2_{time.strftime('%Y%m%d_%H%M%S')}"
    sch = ResearchSchedulerV2(spec, run_dir, resume=args.resume, verbose=not args.quiet)
    out = sch.run()
    _print_final(spec, run_dir, out["final"])
    print(f"research: {out['research'].get('stop_reason')}")
    return 0


def cmd_run(args):
    from .scheduler import ResearchScheduler
    spec = _spec_from_args(args)
    if spec.pipeline == "v2":
        return cmd_research(args)
    run_dir = Path(args.run_dir) if args.run_dir else HARNESS_ROOT / "runs" / f"{spec.name}_{time.strftime('%Y%m%d_%H%M%S')}"
    sch = ResearchScheduler(spec, run_dir, resume=args.resume, verbose=not args.quiet)
    out = sch.run()
    fin = out["final"]
    print("\n=== research complete ===")
    print(f"run dir : {run_dir}")
    print(f"report  : {run_dir / 'report.md'}")
    print(f"model   : {fin['model_path']}  ({fin['kind']}: {', '.join(fin['members'])})")
    print(f"val {spec.primary}: {fin['val']:.5g}   test: " +
          ", ".join(f"{k}={v:.5g}" for k, v in fin["test"].items() if v is not None))
    if spec.success["threshold"] is not None:
        print(f"success criterion met: {fin['audit']['success']}")
    return 0


def cmd_init(args):
    from .spec import TEMPLATE, compile_spec, llm_fill_spec
    from .llm import make_llm
    import yaml
    out = Path(args.out)
    raw = {"name": args.name, "problem": args.problem}
    llm = make_llm({"backend": args.backend or "auto"})
    if not llm.is_null:
        print(f"compiling spec with {llm.describe()} ...")
        raw = llm_fill_spec(raw, llm)
        compile_spec(raw)   # validate
        out.write_text("# Generated by `mlharness init`; edit freely.\n" + yaml.safe_dump(raw, sort_keys=False))
    else:
        out.write_text(TEMPLATE.format(name=args.name, problem=args.problem.replace("\n", " ")))
        print("no LLM backend available: wrote a template; fill in the simulator section")
    print(f"wrote {out}")
    return 0


def cmd_status(args):
    p = Path(args.run_dir) / "status.json"
    print(p.read_text() if p.exists() else f"no status.json in {args.run_dir}")
    return 0


def cmd_report(args):
    p = Path(args.run_dir) / "report.md"
    if args.rebuild:
        from .state import rebuild_report
        from .llm import make_llm
        llm = make_llm({"backend": args.backend}) if args.backend else None
        spec_d = json.loads((Path(args.run_dir) / "spec.json").read_text())
        if spec_d.get("pipeline") == "v2":
            print("V2 reports are written at the end of each run; research_trace.json holds the full research record. "
                  "Rebuilding the research section from artifacts:")
            from .agents.reporter_v2 import research_state_from_store
            from .artifacts import FileSystemStore
            st = research_state_from_store(FileSystemStore(Path(args.run_dir), resume=True))
            print(json.dumps({"rounds": len(st["rounds"]), "proposal_versions": len(st["proposals"]),
                              "abandoned": len(st["abandoned"]), "stop_reason": st["stop_reason"]}, indent=1))
            return 0
        rebuild_report(args.run_dir, llm)
        print(f"rebuilt {p} from artifacts")
        return 0
    print(p.read_text(encoding="utf-8") if p.exists() else f"no report.md in {args.run_dir}")
    return 0


def cmd_memory(args):
    from .memory import ResearchMemory
    mem = ResearchMemory(path=args.path, write=False)
    if args.action == "stats":
        print(json.dumps(mem.stats(), indent=1))
    elif args.action == "show":
        rec = mem.get(args.query)
        print(json.dumps(rec, indent=1, default=str) if rec else f"no record {args.query}")
        if rec:
            print("lineage:", [r["id"] for r in mem.lineage(rec["id"])])
    else:
        types = args.type.split(",") if args.type else None
        for r in mem.search(args.query or "", k=args.k, types=types):
            r = ResearchMemory.redacted(r) if not args.show_test else r
            print(f"{r['id']}  {r['type']:12s} {str(r.get('status')):24s} run={r.get('run_id')}  score={r['_score']}\n"
                  f"    {r['title'][:150]}")
            if args.verbose:
                print("    " + json.dumps(r.get("data"), default=str)[:700])
    return 0


def cmd_literature(args):
    from .tools import TheoremSearchClient, assess_applicability
    c = TheoremSearchClient(base_url=args.base_url, cache_dir=None if args.no_cache else "default")
    facts = {}
    if args.spec:
        from .problem import ProblemContext
        from .spec import load_raw
        facts = ProblemContext(load_raw(args.spec)["simulator"], authorized=False).facts
    r = c.search(args.query, args.n)
    if not r.ok:
        print(f"retrieval failed ({r.error_kind}): {r.error}")
        return 1
    print(f"{len(r.refs)} results via {r.endpoint} in {r.latency:.1f}s{' (cached)' if r.cached else ''}")
    for ref in r.refs:
        a = assess_applicability(ref, facts) if facts else None
        print(f"\n[{ref.ref_id}] {ref.citation()}\n  {(ref.slogan or ref.body or '')[:400]}")
        if a:
            print(f"  applicability screen: {a['applies']}  conflicts={a['conflicts']}  matched={a['matched']}")
    return 0


def cmd_remote_check(args):
    from .remote import AMATH_SERVERS, RemoteRunner
    hosts = [args.host] if args.host else list(AMATH_SERVERS)
    for h in hosts:
        rr = RemoteRunner({"enabled": True, "host": h, "username_env": args.user_env, "password_env": args.password_env,
                           "env_file": args.env_file, "python": args.python})
        info = rr.probe()
        rr.close()
        print(json.dumps(info, indent=1))
    return 0


def cmd_trace(args):
    from .artifacts import FileSystemStore
    store = FileSystemStore(Path(args.run_dir), resume=True)
    if args.idea:
        items = store.idea_history(args.idea)
    else:
        target = args.artifact or (store.latest("checkpoint").id if store.latest("checkpoint") else None)
        if target is None:
            print("no checkpoint in this run; pass --artifact or --idea")
            return 1
        items = store.lineage(target)
    for a in items:
        print(f"{a.id:12s} {a.kind:10s} {a.author:20s} {a.idea_id or '-':9s} {a.summary}")
        if args.verbose:
            print("    " + json.dumps(a.data, default=str)[:600])
    return 0


def cmd_predict(args):
    import numpy as np
    from .export import load_model
    model = load_model(args.run_dir)
    src = Path(args.input)
    if src.suffix == ".npz":
        with np.load(src) as z:
            X = z[args.key]
    elif src.suffix == ".npy":
        X = np.load(src)
    else:
        X = np.loadtxt(src, delimiter=",")
    pred = model.predict(X)
    np.save(args.output, pred)
    print(f"predicted {len(pred)} rows -> {args.output}")
    return 0


def cmd_doctor(args):
    from .resources import detect_hardware
    from .llm import find_claude_cli, find_codex_cli, _anthropic_ready
    from .methods import methods_for
    from .tools import TheoremSearchClient
    from .memory import ResearchMemory
    ping = TheoremSearchClient(cache_dir=None, timeout=15).ping()
    print("theoremsearch   :", "reachable" if ping.ok else f"UNREACHABLE ({ping.error_kind}: {ping.error})")
    print("research memory :", json.dumps(ResearchMemory(write=False).stats()))
    try:
        import paramiko  # noqa: F401
        print("paramiko (remote GPU):", paramiko.__version__)
    except ImportError:
        print("paramiko (remote GPU): not installed (pip install paramiko)")
    hw = detect_hardware()
    print(json.dumps(hw, indent=1))
    print("claude code CLI :", find_claude_cli())
    print("codex CLI       :", find_codex_cli())
    print("anthropic SDK + credentials:", _anthropic_ready())
    print("regression methods    :", list(methods_for("regression")))
    print("classification methods:", list(methods_for("classification")))
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(prog="mlharness", description="Autonomous ML research harness (V2: research-first)")
    sub = ap.add_subparsers(dest="cmd", required=True)

    rs = sub.add_parser("research", help="V2: research-first run (4 researchers + critic -> portfolio -> execution)")
    rs.add_argument("--spec", required=True)
    rs.add_argument("--run-dir")
    rs.add_argument("--backend", choices=["auto", "none", "claude_code", "anthropic", "codex"])
    rs.add_argument("--model")
    rs.add_argument("--budget", type=float, help="override budget.compute_seconds (execution compute)")
    rs.add_argument("--workers", type=int)
    rs.add_argument("--rounds", type=int, help="override research.max_rounds")
    rs.add_argument("--research-llm-calls", type=int, dest="research_llm_calls")
    rs.add_argument("--memory", help="research-memory JSONL path (default .research_memory/memory.jsonl)")
    rs.add_argument("--no-memory", action="store_true", dest="no_memory")
    rs.add_argument("--no-literature", action="store_true", dest="no_literature")
    rs.add_argument("--no-forward-model", action="store_true", dest="no_forward_model",
                    help="deny methods access to the simulator's forward operator")
    rs.add_argument("--remote", help="dispatch GPU jobs to this SSH host (e.g. americano, doppio)")
    rs.add_argument("--resume", action="store_true")
    rs.add_argument("--quiet", action="store_true")
    rs.set_defaults(fn=cmd_research)

    mm = sub.add_parser("memory", help="query the cross-run research memory")
    mm.add_argument("action", choices=["search", "show", "stats"])
    mm.add_argument("query", nargs="?", default="")
    mm.add_argument("--path")
    mm.add_argument("--type", help="comma-separated record types")
    mm.add_argument("-k", type=int, default=10)
    mm.add_argument("--show-test", action="store_true", help="do not redact test-set numbers")
    mm.add_argument("-v", "--verbose", action="store_true")
    mm.set_defaults(fn=cmd_memory)

    lt = sub.add_parser("literature", help="query TheoremSearch directly")
    lt.add_argument("query")
    lt.add_argument("-n", type=int, default=5)
    lt.add_argument("--spec", help="screen applicability against this spec's simulator facts")
    lt.add_argument("--base-url", default="https://api.theoremsearch.com")
    lt.add_argument("--no-cache", action="store_true")
    lt.set_defaults(fn=cmd_literature)

    rc = sub.add_parser("remote-check", help="probe SSH GPU servers (credentials from .env by variable name)")
    rc.add_argument("--host", help="americano | cubano | doppio | galao | full hostname (default: all AMATH servers)")
    rc.add_argument("--user-env", default="SERVICE_USERNAME")
    rc.add_argument("--password-env", default="SERVICE_PASSWORD")
    rc.add_argument("--env-file", default="auto")
    rc.add_argument("--python", default="python3")
    rc.set_defaults(fn=cmd_remote_check)

    r = sub.add_parser("run", help="run the full research pipeline for a spec")
    r.add_argument("--spec", required=True)
    r.add_argument("--run-dir")
    r.add_argument("--backend", choices=["auto", "none", "claude_code", "anthropic", "codex"])
    r.add_argument("--model", help="model name passed to the LLM backend")
    r.add_argument("--budget", type=float, help="override budget.compute_seconds")
    r.add_argument("--workers", type=int)
    r.add_argument("--resume", action="store_true", help="continue a run dir, reusing completed experiments")
    r.add_argument("--quiet", action="store_true")
    r.set_defaults(fn=cmd_run)

    i = sub.add_parser("init", help="create a spec file from a free-text problem statement")
    i.add_argument("--problem", required=True)
    i.add_argument("--name", default="research")
    i.add_argument("--out", default="spec.yaml")
    i.add_argument("--backend", choices=["auto", "none", "claude_code", "anthropic", "codex"])
    i.set_defaults(fn=cmd_init)

    s = sub.add_parser("status", help="show live status of a run")
    s.add_argument("run_dir")
    s.set_defaults(fn=cmd_status)
    s = sub.add_parser("report", help="print a run's report (or --rebuild it from the artifacts)")
    s.add_argument("run_dir")
    s.add_argument("--rebuild", action="store_true", help="regenerate report.md from artifacts.jsonl")
    s.add_argument("--backend", choices=["none", "claude_code", "anthropic", "codex"],
                   help="with --rebuild: LLM used to write the discussion section")
    s.set_defaults(fn=cmd_report)

    t = sub.add_parser("trace", help="trace artifact lineage (default: the final model)")
    t.add_argument("run_dir")
    t.add_argument("--artifact")
    t.add_argument("--idea")
    t.add_argument("-v", "--verbose", action="store_true")
    t.set_defaults(fn=cmd_trace)

    p = sub.add_parser("predict", help="predict with a run's final model")
    p.add_argument("run_dir")
    p.add_argument("--input", required=True, help=".npy, .npz (with --key) or .csv of raw features")
    p.add_argument("--key", default="X_test")
    p.add_argument("--output", default="predictions.npy")
    p.set_defaults(fn=cmd_predict)

    d = sub.add_parser("doctor", help="show detected hardware, backends and methods")
    d.set_defaults(fn=cmd_doctor)

    args = ap.parse_args(argv)
    return args.fn(args)


if __name__ == "__main__":
    sys.exit(main())
